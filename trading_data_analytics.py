import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt
import os

# ==========================================

# 1. SYNTHETIC DATA GENERATION (10 Marks)

#==========================================

print("--- Generating Synthetic Trading Business Data ---")
np.random.seed(42)
num_clients = 1000

#Generating features for the business strategy (DII/FII Mediator Model)

data = {
'Client_ID': [f'CL_{i:04d}' for i in range(1, num_clients + 1)],
'Age': np.random.randint(25, 75, num_clients),
'Annual_Income_USD': np.random.normal(150000, 50000, num_clients),
'Allocated_Capital_USD': np.random.exponential(scale=50000, size=num_clients) + 10000,
'Risk_Tolerance': np.random.choice(['Low', 'Medium', 'High'], num_clients, p=[0.3, 0.5, 0.2]),
'Preferred_Asset_Class': np.random.choice(['Equities', 'Forex', 'Commodities', 'Crypto'], num_clients),
'Months_Active': np.random.randint(1, 60, num_clients),
}

df = pd.DataFrame(data)

#Simulating Business Outcomes based on generated features (Diagnostic relationships)

#Higher risk generally yields higher variance in ROI. More capital means slightly lower percentage commission.

df['Avg_Monthly_ROI'] = np.where(df['Risk_Tolerance'] == 'High', np.random.normal(2.0, 3.5, num_clients),
np.where(df['Risk_Tolerance'] == 'Medium', np.random.normal(1.0, 1.5, num_clients),
np.random.normal(0.5, 0.5, num_clients)))

##Commission is a percentage of capital traded, higher activity (Months) = more total commission

base_commission_rate = 0.005 # 0.5%
df['Total_Commission_Generated'] = df['Allocated_Capital_USD'] * base_commission_rate * df['Months_Active'] * np.random.uniform(0.8, 1.2, num_clients)

#Introduce some messy data to fulfill the Data Cleaning requirement

df.loc[10:30, 'Age'] = np.nan
df.loc[50:70, 'Annual_Income_USD'] = -5000 # Erroneous negative values
df.loc[100:150, 'Preferred_Asset_Class'] = np.nan

#Save raw data

df.to_csv('raw_trading_data.csv', index=False)
print("Raw synthetic data generated and saved to 'raw_trading_data.csv'\n")

# ==========================================

# 2. DATA PREPARATION & CLEANING (10 Marks)

# ==========================================

print("--- Preparing and Cleaning Data ---")

#A. Handling Missing Values

#Fill missing Age with median age

df['Age'] = df['Age'].fillna(df['Age'].median())

#Fill missing Asset Classes with the mode (most frequent)

mode_asset = df['Preferred_Asset_Class'].mode()[0]
df['Preferred_Asset_Class'] = df['Preferred_Asset_Class'].fillna(mode_asset)

#B. Handling Anomalies / Erroneous Data

#Convert negative incomes to median income

median_income = df[df['Annual_Income_USD'] > 0]['Annual_Income_USD'].median()
df['Annual_Income_USD'] = df['Annual_Income_USD'].apply(lambda x: median_income if x <= 0 else x)

#C. Data Transformation / Feature Engineering

#Encode categorical variables for correlation analysis later

risk_mapping = {'Low': 1, 'Medium': 2, 'High': 3}
df['Risk_Score_Numeric'] = df['Risk_Tolerance'].map(risk_mapping)

#Save cleaned data

df.to_csv('cleaned_trading_data.csv', index=False)
print("Data cleaned, transformed, and saved to 'cleaned_trading_data.csv'\n")

# ==========================================

# 3. DESCRIPTIVE & DIAGNOSTIC ANALYTICS (30 Marks)

# ==========================================

print("--- Performing EDA & Diagnostic Analytics ---")

#Set aesthetic parameters for graphs

sns.set_theme(style="whitegrid")

#Create a directory to save plots

if not os.path.exists("EDA_Plots"):
    os.makedirs("EDA_Plots")

#1. Descriptive: Distribution of Allocated Capital

plt.figure(figsize=(10, 6))
sns.histplot(df['Allocated_Capital_USD'], bins=50, kde=True, color='blue')
plt.title('Distribution of Client Allocated Capital')
plt.xlabel('Capital (USD)')
plt.ylabel('Frequency')
plt.savefig('EDA_Plots/Capital_Distribution.png')
plt.close()
print("Saved: Capital_Distribution.png - Highlights right-skewed capital allocation.")

#2. Diagnostic: Risk Tolerance vs. Average Monthly ROI

plt.figure(figsize=(10, 6))
sns.boxplot(x='Risk_Tolerance', y='Avg_Monthly_ROI', data=df, order=['Low', 'Medium', 'High'], palette='Set2')
plt.title('Diagnostic: Risk Tolerance vs Return on Investment')
plt.xlabel('Risk Tolerance Level')
plt.ylabel('Average Monthly ROI (%)')
plt.savefig('EDA_Plots/Risk_vs_ROI.png')
plt.close()
print("Saved: Risk_vs_ROI.png - Diagnoses the relationship between client risk profile and actual market returns.")

#3. Descriptive: Revenue by Asset Class

plt.figure(figsize=(10, 6))
asset_revenue = df.groupby('Preferred_Asset_Class')['Total_Commission_Generated'].sum().reset_index()
sns.barplot(x='Preferred_Asset_Class', y='Total_Commission_Generated', data=asset_revenue, palette='viridis')
plt.title('Total Commission Revenue Generated by Asset Class')
plt.xlabel('Asset Class')
plt.ylabel('Total Commission (USD)')
plt.savefig('EDA_Plots/Revenue_by_Asset.png')
plt.close()
print("Saved: Revenue_by_Asset.png - Identifies the most profitable market segments.")

#4. Diagnostic: Correlation Heatmap

#Select only numerical columns for correlation

num_cols = ['Age', 'Annual_Income_USD', 'Allocated_Capital_USD', 'Months_Active', 'Avg_Monthly_ROI', 'Total_Commission_Generated', 'Risk_Score_Numeric']
corr_matrix = df[num_cols].corr()

plt.figure(figsize=(10, 8))
sns.heatmap(corr_matrix, annot=True, cmap='coolwarm', fmt=".2f", linewidths=0.5)
plt.title('Correlation Matrix of Trading Features')
plt.tight_layout()
plt.savefig('EDA_Plots/Correlation_Heatmap.png')
plt.close()
print("Saved: Correlation_Heatmap.png - Diagnoses linear relationships (e.g., Capital and Commission).")

print("\n--- Individual Assignment Code Execution Complete ---")